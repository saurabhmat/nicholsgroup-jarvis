// Bundles packages/modules/brain/templates/** (except the README) into src/domain/templates.generated.ts, so the
// server can create the seed pages without reading the file system at run time (serverless bundles do not ship it).
// Usage: node packages/modules/brain/scripts/build-templates.mjs [--check]   (--check exits 1 when the file is stale)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const templatesDir = path.join(here, "..", "templates");
const out = path.join(here, "..", "src", "domain", "templates.generated.ts");

const files = readdirSync(templatesDir, { recursive: true })
  .map((f) => String(f).split(path.sep).join("/"))
  .filter((f) => f.endsWith(".md") && f !== "README.md")
  .sort();

const body = [
  "// GENERATED by packages/modules/brain/scripts/build-templates.mjs from ../../templates. Do not edit by hand.",
  "// Synthetic placeholder text only (CLAUDE.md rule 10).",
  "export const TEMPLATE_FILES: Readonly<Record<string, string>> = {",
  ...files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(path.join(templatesDir, f), "utf8"))},`),
  "};",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {
    // missing counts as stale
  }
  if (current !== body) {
    console.error("templates.generated.ts is out of date. Run: node packages/modules/brain/scripts/build-templates.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(out, body);
  console.log(`wrote ${path.relative(process.cwd(), out)} (${String(files.length)} files)`);
}
