// Guard: generated seed SQL may contain only synthetic data (CLAUDE.md rule 10). Runs inside the generator (fails
// closed) and in tests. It is a HEURISTIC: it cannot see lower-case names, or names assembled with chr() or ||,
// so new seed sections still need review. Checks:
//  1. every email address anywhere (comments too) is on exactly `example.test`;
//  2. no E'', U&'' or dollar-quoted strings (all literals come from lit(); only the generator header uses $fence$);
//  3. every domain-like token inside a string literal is on a reserved name (RFC 2606 / 6761);
//  4. every capitalized word (Unicode) inside a literal, comment or quoted identifier is a lane name word, lane code
//     or persona label word;
//  5. no SSN-like numbers or runs of 9+ digits inside literals (UUIDs excepted);
//  6. known real people / company domains appear nowhere (case-insensitive).
import { ALLOWED_NAME_WORDS, SYNTHETIC_EMAIL_DOMAIN } from "./data.mjs";
import { COMMENT_TYPES, tokenize } from "./lexer.mjs";

/**
 * Generator-owned header: the only text exempt from checks 2–5 (checks 1 and 6 still cover it). The fence aborts the
 * seed when the target database already has any user that is not a synthetic `example.test` user, so applying it
 * to a real project fails instead of mixing synthetic users into real data.
 */
export const GENERATOR_HEADER = [
  "-- GENERATED by `pnpm db:seed` (supabase/core/seed/generate.mjs). Do not edit by hand.",
  "-- Synthetic data only (CLAUDE.md rule 10). Local only: applied by `supabase db reset --local` via [db.seed].",
  "-- Never apply it with --include-seed, --linked or --db-url.",
  "set standard_conforming_strings = on;",
  "do $fence$ begin if exists (select 1 from auth.users where email is null or email not like '%@example.test') " +
    "then raise exception 'synthetic seed refuses: non-synthetic users present'; end if; end $fence$;",
  "",
].join("\n");

const RESERVED_TLDS = new Set(["test", "example", "invalid", "localhost"]);
const RESERVED_DOMAINS = new Set(["example.com", "example.net", "example.org"]);

// People and organisations from the planning docs. Matching is substring and case-insensitive.
const DENYLIST = ["robert", "sophie", "saurabh", "gopal", "pubkgroup", "pub-k.org", "pub-k.com", "nicholscapital", "nicholsgroup", "nicholslaw"];

const EMAIL_RE = /[^\s'"`@(),;<>]+@([^\s'"`@(),;<>]+)/gu;
const DOMAIN_RE = /(?:[\p{L}\p{N}-]+\.)+\p{L}{2,}/gu;
const CAPITALIZED_RE = /(?<![\p{L}\p{N}_])\p{Lu}[\p{L}\p{M}]*/gu;
const UUID_RE = /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/gi;
const SSN_RE = /(?<!\d)\d{3}-\d{2}-\d{4}(?!\d)/;
const LONG_DIGITS_RE = /\d{9,}/;

const isReservedDomain = (domain) => {
  const d = domain.toLowerCase();
  const tld = d.split(".").pop();
  return RESERVED_TLDS.has(tld) || [...RESERVED_DOMAINS].some((r) => d === r || d.endsWith(`.${r}`));
};

/** @returns {string[]} human-readable violations; empty when the SQL is clean. */
export function findSyntheticViolations(sql) {
  const out = [];
  const allowedWords = new Set(ALLOWED_NAME_WORDS);

  // Whole text, header included.
  for (const m of sql.matchAll(EMAIL_RE)) {
    if (m[1] !== SYNTHETIC_EMAIL_DOMAIN) out.push(`email not on ${SYNTHETIC_EMAIL_DOMAIN}: ${m[0]}`);
  }
  const lower = sql.toLowerCase();
  for (const term of DENYLIST) {
    if (lower.includes(term)) out.push(`denylisted real name or domain: ${term}`);
  }

  const body = sql.startsWith(GENERATOR_HEADER) ? sql.slice(GENERATOR_HEADER.length) : sql;
  let tokens;
  try {
    tokens = tokenize(body);
  } catch (err) {
    return [...new Set([...out, `unparseable SQL: ${err.message}`])];
  }

  const checkNames = (text) => {
    for (const w of text.match(CAPITALIZED_RE) ?? []) {
      if (!allowedWords.has(w)) out.push(`name-like word not allowed: ${w}`);
    }
  };

  for (const t of tokens) {
    if (t.type === "estring" || t.type === "ustring" || t.type === "dollar") {
      out.push(`${t.type} literal not allowed (use lit()): ${t.raw.slice(0, 40)}`);
    }
    if (t.type === "code") continue;
    checkNames(t.value);
    if (t.type === "ident" || COMMENT_TYPES.has(t.type)) continue;
    // Literals.
    for (const d of t.value.match(DOMAIN_RE) ?? []) {
      if (!isReservedDomain(d)) out.push(`non-reserved domain in literal: ${d}`);
    }
    const digits = t.value.replace(UUID_RE, "");
    if (SSN_RE.test(digits)) out.push(`SSN-like number in literal: ${t.raw.slice(0, 40)}`);
    if (LONG_DIGITS_RE.test(digits)) out.push(`run of 9+ digits in literal: ${t.raw.slice(0, 40)}`);
  }
  return [...new Set(out)];
}

export function assertSyntheticOnly(sql) {
  const violations = findSyntheticViolations(sql);
  if (violations.length > 0) {
    throw new Error(`seed output is not synthetic-only:\n  - ${violations.join("\n  - ")}`);
  }
}
